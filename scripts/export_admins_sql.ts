// auth/scripts/export_admins_sql.ts
// Reads RAG Postgres users table and emits a D1-compatible SQL file for import.
// Usage:
//   PG_URL="postgresql://user:pw@host:5433/db" npx tsx scripts/export_admins_sql.ts
// Then:
//   npx wrangler d1 execute bridgingchina-auth --remote --file=./scripts/migrate_admins.sql
//
// Design decisions (2026-04-19 brainstorming, ratified by code review):
//   - password NOT migrated; admins re-authenticate via /auth/forgot-password
//   - email placeholder {username}@migrate.bridgingchina.net; user updates via reset-password
//   - role='admin' for ALL migrated users (pre-refactor all DB users WERE admins)
//   - emailVerified=0: force email verification on first password reset flow
//   - INSERT OR IGNORE for safe re-runs

import { Client } from "pg";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

function escapeSqlString(s: string): string {
  return "'" + s.replace(/'/g, "''") + "'";
}

function nullableStr(s: string | null): string {
  return s === null ? "NULL" : escapeSqlString(s);
}

function nullableInt(ts: Date | null): string {
  return ts === null ? "NULL" : String(ts.getTime());
}

async function main() {
  const pgUrl = process.env.PG_URL;
  if (!pgUrl) {
    console.error("PG_URL env var required (format: postgresql://user:pw@host:5433/dbname)");
    process.exit(1);
  }

  const pg = new Client({ connectionString: pgUrl });
  await pg.connect();

  // Column names verified against RAG/app/models/user.py (User model, 'users' table):
  //   id UUID (via UUIDMixin), username, display_name, is_active,
  //   password_changed_at (nullable TIMESTAMPTZ).
  // `hashed_password` is intentionally NOT selected — passwords are discarded.
  const { rows } = await pg.query<{
    id: string;
    username: string;
    display_name: string | null;
    is_active: boolean;
    password_changed_at: Date | null;
  }>(
    "SELECT id::text AS id, username, display_name, is_active, password_changed_at FROM users ORDER BY username"
  );

  await pg.end();

  if (rows.length === 0) {
    console.warn("No users found in Postgres. Nothing to migrate.");
    process.exit(0);
  }

  const now = Date.now();
  const stmts = rows.map((row) => {
    const email = `${row.username}@migrate.bridgingchina.net`;
    return `INSERT OR IGNORE INTO user (id, email, emailVerified, name, image, createdAt, updatedAt, username, role, isActive, passwordChangedAt, displayUsername) VALUES (${escapeSqlString(row.id)}, ${escapeSqlString(email)}, 0, ${nullableStr(row.display_name)}, NULL, ${now}, ${now}, ${escapeSqlString(row.username)}, 'admin', ${row.is_active ? 1 : 0}, ${nullableInt(row.password_changed_at)}, NULL);`;
  });

  const header = [
    `-- Generated by scripts/export_admins_sql.ts on ${new Date().toISOString()}`,
    `-- Source: RAG Postgres users table (${rows.length} rows)`,
    `-- Target: auth/ D1 user table`,
    `-- REVIEW CAREFULLY before running wrangler d1 execute --file=`,
    "",
  ].join("\n");

  const outPath = resolve("./scripts/migrate_admins.sql");
  await writeFile(outPath, header + stmts.join("\n") + "\n", "utf8");

  console.log(`Exported ${rows.length} admins to ${outPath}`);
  console.log("");
  console.log("Next step - review then apply:");
  console.log(`  cat ${outPath}`);
  console.log(`  npx wrangler d1 execute bridgingchina-auth --remote --file=./scripts/migrate_admins.sql`);
  console.log("");
  console.log("After apply, notify migrated admins to reset password via:");
  console.log(`  https://auth.bridgingchina.net/auth/forgot-password`);
  console.log("(their email is {username}@migrate.bridgingchina.net until they update it)");
}

main().catch((e) => {
  console.error("Migration failed:", e);
  process.exit(1);
});
