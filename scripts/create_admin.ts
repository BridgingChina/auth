// auth/scripts/create_admin.ts
// CLI to bootstrap an admin user directly into the auth D1 database, bypassing
// Better Auth's normal sign-up flow. Phase 2 of the unified-auth refactor removes
// `RAG/scripts/create_user.py`, so this is the replacement path for creating new
// admins after that point.
//
// Usage:
//   cd auth
//   npx tsx scripts/create_admin.ts \
//     --email admin@bridgingchina.net \
//     --username admin \
//     --name "Main Admin"
//
// Then apply the generated SQL (the human runs wrangler — the script itself never
// shells out, mirroring export_admins_sql.ts):
//   npx wrangler d1 execute bridgingchina-auth --remote --file=./scripts/create_admin.sql
//
// After apply, the admin visits https://auth.bridgingchina.net/auth/forgot-password
// to set their password (this is what materialises the `account` row with the
// `credential` provider — the script deliberately does NOT create one).
//
// Design decisions:
//   - No password / account row created here. Forcing /auth/forgot-password means
//     password-hashing logic stays in one place (Better Auth) and we never have
//     a plaintext secret near this script.
//   - emailVerified=1: admin emails are trusted at creation time (a human operator
//     typed them). This differs from export_admins_sql.ts where we force re-verify
//     because the source emails were placeholders.
//   - id is a 32-char base64url string (crypto.randomBytes(24).toString("base64url")
//     yields exactly 32 chars), compatible with Better Auth's default nanoid-style
//     id format.
//   - Script never executes shell commands on user input: it only writes a SQL file.

import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parseArgs } from "node:util";

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const USERNAME_RE = /^[A-Za-z0-9_]{3,30}$/;

function escapeSqlString(s: string): string {
  return "'" + s.replace(/'/g, "''") + "'";
}

function printUsageAndExit(code: number): never {
  const msg = [
    "Usage:",
    "  npx tsx scripts/create_admin.ts --email <email> --name <name> [--username <username>]",
    "",
    "Required:",
    "  --email     Admin's email address (used for forgot-password flow)",
    "  --name      Display name",
    "",
    "Optional:",
    "  --username  3-30 chars, [A-Za-z0-9_] only",
    "",
    "Example:",
    "  npx tsx scripts/create_admin.ts \\",
    "    --email admin@bridgingchina.net \\",
    "    --username admin \\",
    "    --name \"Main Admin\"",
  ].join("\n");
  (code === 0 ? console.log : console.error)(msg);
  process.exit(code);
}

async function main() {
  let parsed;
  try {
    parsed = parseArgs({
      args: process.argv.slice(2),
      options: {
        email: { type: "string" },
        username: { type: "string" },
        name: { type: "string" },
        help: { type: "boolean", short: "h" },
      },
      strict: true,
      allowPositionals: false,
    });
  } catch (e) {
    console.error("Argument error:", (e as Error).message);
    printUsageAndExit(1);
  }

  const { values } = parsed;

  if (values.help) {
    printUsageAndExit(0);
  }

  const email = values.email;
  const name = values.name;
  const username = values.username;

  if (!email || !name) {
    console.error("Error: --email and --name are required.");
    printUsageAndExit(1);
  }

  if (!EMAIL_RE.test(email)) {
    console.error(`Error: --email "${email}" does not look like a valid email.`);
    process.exit(1);
  }

  if (username !== undefined && !USERNAME_RE.test(username)) {
    console.error(
      `Error: --username "${username}" invalid. Must be 3-30 chars, [A-Za-z0-9_] only.`,
    );
    process.exit(1);
  }

  // Better Auth default id format: 32-char nanoid-style alphanumeric.
  // base64url of 24 bytes = 32 chars, alphabet [A-Za-z0-9_-]. Compatible.
  const id = randomBytes(24).toString("base64url");
  const now = Date.now();

  const sql =
    `INSERT INTO user ` +
    `(id, email, emailVerified, name, image, createdAt, updatedAt, username, ` +
    `role, isActive, passwordChangedAt, displayUsername) VALUES (` +
    `${escapeSqlString(id)}, ` +
    `${escapeSqlString(email)}, ` +
    `1, ` +
    `${escapeSqlString(name)}, ` +
    `NULL, ` +
    `${now}, ` +
    `${now}, ` +
    `${username ? escapeSqlString(username) : "NULL"}, ` +
    `'admin', ` +
    `1, ` +
    `NULL, ` +
    `NULL);`;

  const header = [
    `-- Generated by scripts/create_admin.ts on ${new Date().toISOString()}`,
    `-- Target: auth/ D1 user table (bridgingchina-auth)`,
    `-- Creates a single admin user with id=${id}`,
    `-- NO password/account row — admin must use /auth/forgot-password to set password.`,
    `-- REVIEW before running wrangler d1 execute --file=`,
    "",
  ].join("\n");

  const outPath = resolve("./scripts/create_admin.sql");
  await writeFile(outPath, header + sql + "\n", "utf8");

  console.log(`Created admin SQL at ${outPath}`);
  console.log("");
  console.log(`  user.id       = ${id}`);
  console.log(`  user.email    = ${email}`);
  console.log(`  user.username = ${username ?? "(none)"}`);
  console.log(`  user.name     = ${name}`);
  console.log(`  user.role     = admin`);
  console.log("");
  console.log("Next steps:");
  console.log(`  1. Review: cat ${outPath}`);
  console.log(`  2. Apply:  npx wrangler d1 execute bridgingchina-auth --remote --file=./scripts/create_admin.sql`);
  console.log(`  3. Notify the new admin to set their password at:`);
  console.log(`     https://auth.bridgingchina.net/auth/forgot-password`);
  console.log(`     (enter ${email} — the reset email creates the account row with the credential provider)`);
}

main().catch((e) => {
  console.error("create_admin failed:", e);
  process.exit(1);
});
